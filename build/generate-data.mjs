// ─────────────────────────────────────────────────────────────────
//  generate-data.mjs
//
//  The portal's content lives in a few very large source files
//  (interviewQA.js ≈ 800 KB, guideQA.js ≈ 400 KB, sections.js ≈ 300 KB).
//  Importing them anywhere puts ALL of that into the browser, even when a
//  page only needs a count, a title or one subject's worth of content.
//
//  This script loads the source files ONCE at build time and writes small,
//  purpose-built modules to src/constants/generated/:
//
//    catalog.js         tiny: totals + category list           (entry bundle)
//    qa-ids.js          every Q&A id                           (header counter)
//    hub.js             per-topic counts + 3 preview questions (home page)
//    qa-cards.js        id/category/difficulty/question/pills  (Q&A + checklist)
//    search-index.js    id/title/sub/colour + lowercase text   (header search)
//    qa/<category>.js   full Q&A items of ONE category         (loaded on demand)
//    sections/<topic>.js full sections of ONE topic            (loaded on demand)
//
//  The source files stay the single source of truth — edit those as before.
//  The Vite plugin in vite.config.js re-runs this automatically on
//  `npm run dev`, `npm run build`, and whenever a source file changes.
// ─────────────────────────────────────────────────────────────────
import { createServer } from 'vite';
import fs from 'node:fs';
import path from 'node:path';

const HEADER = '// AUTO-GENERATED by build/generate-data.mjs — do not edit (edit src/constants/* instead).\n';

export const slugify = (text) =>
  String(text).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

/** JSON.stringify that refuses anything JSON would silently change. */
function strictJson(value, label) {
  return JSON.stringify(value, (key, v) => {
    if (typeof v === 'function' || typeof v === 'symbol' || typeof v === 'bigint') {
      throw new Error(`[generate-data] ${label}: "${key}" is a ${typeof v}, which cannot be serialised`);
    }
    return v;
  });
}

/** Module whose default export is parsed with JSON.parse — much cheaper for the
 *  browser to parse than an equally large object literal. */
const jsonModule = (value, label) =>
  `${HEADER}export default JSON.parse(${JSON.stringify(strictJson(value, label))});\n`;

function writeIfChanged(file, content) {
  try {
    if (fs.readFileSync(file, 'utf8') === content) return false;
  } catch { /* new file */ }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return true;
}

function removeStale(dir, keep) {
  if (!fs.existsSync(dir)) return false;
  let removed = false;
  for (const name of fs.readdirSync(dir)) {
    if (!keep.has(name)) {
      fs.rmSync(path.join(dir, name), { recursive: true, force: true });
      removed = true;
    }
  }
  return removed;
}

/** Returns true when any generated file changed. */
export async function generateData(root) {
  const server = await createServer({
    root,
    configFile: false,          // never re-load vite.config.js (would recurse into the plugin)
    logLevel: 'silent',
    appType: 'custom',
    optimizeDeps: { noDiscovery: true, include: [] },
    server: { middlewareMode: true, watch: null, hmr: false, ws: false },
  });

  let QA; let SECTIONS; let TOPICS;
  try {
    ({ INTERVIEW_QA: QA } = await server.ssrLoadModule('/src/constants/interviewQA.js'));
    ({ SECTIONS } = await server.ssrLoadModule('/src/constants/sections.js'));
    ({ TOPICS } = await server.ssrLoadModule('/src/constants/topics.js'));
  } finally {
    await server.close();
  }

  const out = path.join(root, 'src/constants/generated');
  let changed = false;
  const write = (rel, content) => { changed = writeIfChanged(path.join(out, rel), content) || changed; };

  // ── Q&A: one module per category, each item tagged with its global position
  //    so topics that span several categories keep the original ordering.
  const byCategory = new Map();
  QA.forEach((item, index) => {
    if (!byCategory.has(item.category)) byCategory.set(item.category, []);
    byCategory.get(item.category).push({ ...item, _i: index });
  });

  const categories = [...byCategory.keys()].map((key) => ({
    key,
    slug: slugify(key),
    count: byCategory.get(key).length,
  }));
  const slugs = new Set(categories.map((c) => c.slug));
  if (slugs.size !== categories.length) throw new Error('[generate-data] two Q&A categories share a slug');

  for (const c of categories) write(`qa/${c.slug}.js`, jsonModule(byCategory.get(c.key), `qa/${c.slug}`));
  changed = removeStale(path.join(out, 'qa'), new Set(categories.map((c) => `${c.slug}.js`))) || changed;

  // ── Sections: one module per topic, in the topic's own order.
  const sectionById = new Map(SECTIONS.map((s) => [s.id, s]));
  for (const topic of TOPICS) {
    const list = topic.ids.map((id) => sectionById.get(id)).filter(Boolean);
    write(`sections/${topic.key}.js`, jsonModule(list, `sections/${topic.key}`));
  }
  changed = removeStale(path.join(out, 'sections'), new Set(TOPICS.map((t) => `${t.key}.js`))) || changed;

  // ── Small shared modules
  const answered = QA.filter((q) => typeof q.answer === 'string' && q.answer.trim()).length;

  write('catalog.js',
    `${HEADER}export const QA_TOTAL = ${QA.length};\n`
    + `export const QA_ANSWERED = ${answered};\n`
    + `export const SECTION_TOTAL = ${SECTIONS.length};\n`
    + `export const QA_CATEGORIES = ${strictJson(categories, 'catalog')};\n`);

  write('qa-ids.js', jsonModule(QA.map((q) => q.id), 'qa-ids'));

  const hub = {};
  for (const topic of TOPICS) {
    const matching = QA.filter((q) => topic.qaCategories.includes(q.category));
    hub[topic.key] = {
      qaCount: matching.length,
      preview: matching.slice(0, 3).map((q) => ({ id: q.id, question: q.question })),
    };
  }
  write('hub.js',
    `${HEADER}export const HUB = ${strictJson(hub, 'hub')};\n`
    + `export const SECTION_IDS = ${strictJson(SECTIONS.map((s) => s.id), 'hub-ids')};\n`);

  // rows: [id, category, difficulty, question, highlights(≤3)]
  write('qa-cards.js', jsonModule(
    QA.map((q) => [q.id, q.category, q.difficulty, q.question, (q.highlights || []).slice(0, 3)]),
    'qa-cards',
  ));

  write('search-index.js', jsonModule(
    SECTIONS.map((s) => ({
      id: s.id,
      title: s.title,
      sub: s.sub,
      color: s.color,
      h: [s.title, s.sub, ...(s.concepts || []).map((c) => c.title || '')].join('\n').toLowerCase(),
    })),
    'search-index',
  ));

  return changed;
}
